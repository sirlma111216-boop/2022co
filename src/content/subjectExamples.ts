/**
 * 교과별 예시 데이터.
 *
 * 이론은 하나다. 바뀌는 것은 그 이론을 이해하게 만드는 사례뿐이다.
 * 그래서 화면(컴포넌트)에는 예시 문장을 두지 않고, 전부 이 파일 하나로 모은다.
 * 교과를 하나 더 넣고 싶으면 이 배열에 한 벌을 추가하면 된다 — 페이지는 손대지 않는다.
 *
 * 주의: 과학을 뺀 나머지 교과의 성취기준 문장은 「대표 예시」다.
 * 실제 고시된 성취기준 코드를 임의로 붙이지 않는다. 과학의 [9과10-01] 만
 * 기존 프로젝트에서 검증되어 그대로 유지한다.
 */
import type { Segment } from "@/components/teach/StandardDissect";

export type SubjectId =
  | "korean"
  | "math"
  | "english"
  | "social"
  | "history"
  | "ethics"
  | "science"
  | "techHome"
  | "information"
